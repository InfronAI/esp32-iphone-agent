// Regenerate the board's web icons from the existing iOS app icon on macOS:
//   node hardware/tools/embed_web_icons.cjs
// sips only resizes the existing artwork; the output is embedded in flash.
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {execFileSync} = require('node:child_process');

const root = path.resolve(__dirname, '../..');
const source = path.join(root, 'ios/IPhoneAgent/Assets.xcassets/AppIcon.appiconset/AppIcon.png');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'esp32-web-icons-'));
function resize(size) {
  const file = path.join(temp, `${size}.png`);
  execFileSync('/usr/bin/sips', ['-z', String(size), String(size), source, '--out', file], {stdio: 'pipe'});
  return fs.readFileSync(file);
}
function array(name, bytes) {
  const rows = [];
  for (let i = 0; i < bytes.length; i += 16) {
    rows.push('  ' + [...bytes.subarray(i, i + 16)].map(b => '0x' + b.toString(16).padStart(2, '0')).join(', ') + ',');
  }
  return `static const unsigned char ${name}[] PROGMEM = {\n${rows.join('\n')}\n};\n`;
}
try {
  const favicon = resize(32), icon = resize(64), touch = resize(180);
  // ICO directory containing a PNG image (supported by current browsers).
  const directory = Buffer.alloc(22);
  directory.writeUInt16LE(1, 2);
  directory.writeUInt16LE(1, 4);
  directory[6] = directory[7] = 32;
  directory.writeUInt16LE(1, 10);
  directory.writeUInt16LE(32, 12);
  directory.writeUInt32LE(favicon.length, 14);
  directory.writeUInt32LE(22, 18);
  const ico = Buffer.concat([directory, favicon]);
  fs.writeFileSync(path.join(root, 'hardware/hid_bridge/src/cloud/control_icons.h'),
    '// Generated by hardware/tools/embed_web_icons.cjs from the iOS app icon.\n#pragma once\n' +
    array('CLOUD_ICON_PNG', icon) + array('CLOUD_TOUCH_ICON_PNG', touch) + array('CLOUD_FAVICON_ICO', ico));
  console.log(`Embedded web icons: ${icon.length + touch.length + ico.length} bytes (64px header, 180px touch, 32px favicon).`);
} finally {
  fs.rmSync(temp, {recursive: true, force: true});
}
